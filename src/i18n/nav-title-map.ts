const NORMALIZED_TEXT_TO_KEY = Object.fromEntries(
  Object.entries(TEXT_TO_KEY).map(([text, key]) => [normalizeText(text), key])
)

export function translateKnownText(text: string | undefined, t: TFunction) {
  if (!text) return text
  const trimmed = text.trim()
  const key = TEXT_TO_KEY[trimmed] ?? TITLE_TO_KEY[trimmed] ?? NORMALIZED_TEXT_TO_KEY[normalizeText(trimmed)] ?? NORMALIZED_TITLE_TO_KEY[normalizeText(trimmed)]
  return key ? t(key) : text
}

function translateChild(child: TNavChildren, t: TFunction): TNavChildren {
  return {
    ...child,
    title: translateMenuTitle(child.title, t),
    children: child.children?.map(item => translateChild(item, t)),
  }
}

export function translateNavItems(items: NavItem[], t: TFunction): NavItem[] {
  return items.map(item => ({
    ...item,
    title: translateMenuTitle(item.title, t),
    children: item.children?.map(child => translateChild(child, t)),
  }))
}
