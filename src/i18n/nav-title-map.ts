function normalizeText(text: string) {
  return text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase()
}

const NORMALIZED_TITLE_TO_KEY = Object.fromEntries(
  Object.entries(TITLE_TO_KEY).map(([title, key]) => [normalizeText(title), key])
)

export function translateMenuTitle(title: string, t: TFunction) {
  const trimmed = title.trim()
  const key = TITLE_TO_KEY[trimmed] ?? NORMALIZED_TITLE_TO_KEY[normalizeText(trimmed)]
  return key ? t(key) : title
}

